#!/usr/bin/env python3
"""Write ColProof/Data.lean: certificate keys for every gadget the proof uses.

Certificates are found by exhaustive search here and re-checked in Lean by
`Loses.of_certificate`; this script is not part of the trusted base.

    python3 proofs/lean/gen/emit_lean.py
"""

from __future__ import annotations

from pathlib import Path

from colsolve import ROWS, Solver
from windows import CASE_WINDOWS, window_masks

OUT = Path(__file__).resolve().parents[1] / "ColProof" / "Data.lean"

# Fixed gadgets (width, Blue mask, White mask), masks as in three_row/manifest.json.
FIXED = {
    "E4": (4, 4095, 2023),
    "Ebar": (4, 4095, 3710),
    "F1": (1, 7, 5),
    "H3": (3, (1 << 9) - 1, (1 << 9) - 1),
    "H7": (7, (1 << 21) - 1, (1 << 21) - 1),
}


def gadgets():
    for name, (w, a, b) in FIXED.items():
        yield name, w, a, b
    for name, spec in CASE_WINDOWS.items():
        _, a, b = window_masks(*spec)
        yield f"W_{name}", spec[0], a, b


def main():
    lines = [
        "import ColProof.Cert",
        "",
        "/-! Generated by `gen/emit_lean.py`: certificate data for every gadget.",
        "Each certificate is checked by compiled evaluation of the checker (`native_decide`). -/",
        "",
        "namespace Col",
        "",
    ]
    for name, w, a, b in gadgets():
        solver = Solver(w)
        keys = solver.certificate(a, b)
        root = (a << (ROWS * w)) | b
        data = " ".join(format(k, "x") for k in keys)
        lines += [
            f"/-- `{name}`: width {w}, Blue mask {a}, White mask {b}; {len(keys)} checkpoints. -/",
            f"def {name}_root : Nat := {root}",
            f"def {name}_keys : Array Nat := parseKeys \"{data}\"",
            f"theorem {name}_accepted : Accepted {w} {name}_keys := by native_decide",
            f"theorem {name}_mem : memArr {name}_keys {name}_root = true := by native_decide",
            f"theorem {name}_loses : Loses adj (gA {w} {name}_root) (gB {w} {name}_root) :=",
            f"  Loses.of_certificate {name}_accepted {name}_mem",
            "",
        ]
        print(f"{name}: width {w}, {len(keys)} keys")
    lines.append("end Col")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
